import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import ts from 'typescript';
import test from 'node:test';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (relative) => readFileSync(join(ROOT, relative), 'utf8');

const importPureTS = (path) => {
  const source = read(path);
  const result = ts.transpileModule(source, {
    compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022},
  });
  const module = {exports: {}};
  new Function('module', 'exports', result.outputText)(module, module.exports);
  return module.exports;
};

const api = importPureTS('src/lesson/timeline.ts');
const valid = () => ({
  series: 'Math Concepts Made Easy',
  level: 'Grades 9–12',
  title: 'Symbolic Reasoning',
  tagline: 'A general lesson example, not math generated by Remotion.',
  introFrames: 60,
  outroFrames: 60,
  chapters: [
    {id: 'concept', stage: 'concept', title: 'The concept',
      learningGoal: 'Understand the key idea', durationInFrames: 105},
    {id: 'practice', stage: 'practice', title: 'Independent practice',
      learningGoal: 'Apply the verified method', durationInFrames: 75},
  ],
});

test('exact chapter boundaries are sequential with no gaps or overlap', () => {
  const timeline = api.buildLessonTimeline(valid());
  assert.deepEqual(timeline.map((x) => [x.kind, x.start, x.durationInFrames]), [
    ['intro', 0, 60], ['chapter', 60, 105], ['chapter', 165, 75], ['outro', 240, 60],
  ]);
  assert.equal(api.getLessonDurationInFrames(valid()), 300);
  assert.equal(timeline.at(-1).start + timeline.at(-1).durationInFrames, 300);
});

test('duration always recomputes from lesson data rather than fixed sample', () => {
  const v = valid();
  v.chapters[0].durationInFrames = 275;
  v.introFrames = 45;
  assert.equal(api.getLessonDurationInFrames(v), 455);
});

test('nonpositive, fractional, or missing lengths fail before rendering', () => {
  for (const duration of [0, -10, 5.3, Number.NaN]) {
    const v = valid();
    v.chapters[0].durationInFrames = duration;
    assert.throws(() => api.getLessonDurationInFrames(v), /integer/);
  }
  for (const key of ['introFrames', 'outroFrames']) {
    const v = valid();
    v[key] = 3;
    assert.throws(() => api.getLessonDurationInFrames(v), /at least 30/);
  }
});

test('duplicate chapter IDs and unknown stage names are rejected', () => {
  const v = valid();
  v.chapters[1].id = 'concept';
  assert.throws(() => api.buildLessonTimeline(v), /unique/);
  const wrongStage = valid();
  wrongStage.chapters[1].stage = 'surprise';
  assert.throws(() => api.buildLessonTimeline(wrongStage), /unsupported/);
});

test('unbounded or invalid user content is rejected before React composition', () => {
  const empty = valid();
  empty.chapters = [];
  assert.throws(() => api.getLessonDurationInFrames(empty), /1–40/);
  const title = valid();
  title.title = '   ';
  assert.throws(() => api.getLessonDurationInFrames(title), /title/);
  const long = valid();
  long.title = 'z'.repeat(161);
  assert.throws(() => api.getLessonDurationInFrames(long), /title/);
  const duplicate = valid();
  duplicate.chapters[0].id = '../../bad/path';
  assert.throws(() => api.getLessonDurationInFrames(duplicate), /URL-safe/);
});

test('composition uses verified original mathematical media, never generated answers', () => {
  const shell = read('src/compositions/PremiumLesson.tsx');
  const stage = read('src/components/SceneFrame.tsx');
  assert.match(shell, /buildLessonTimeline\(props\)/);
  assert.match(shell, /<Sequence/);
  assert.match(stage, /data-visual-slot="manim-pending"/);
  assert.doesNotMatch(shell + stage, /<Video\b|<Audio\b|OffthreadVideo|caption.*Track/i);
});

test('no social shorts, uploader or captions are introduced by Step 2', () => {
  const root = read('src/Root.tsx');
  const shell = read('src/compositions/PremiumLesson.tsx');
  assert.doesNotMatch(root + shell, /PremiumShort|YouTube|from ['"].*uploader/i);
  assert.match(read('README.md'), /Step 3 — Connect Manim outputs into Remotion timeline/);
});
